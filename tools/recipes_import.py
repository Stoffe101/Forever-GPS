#!/usr/bin/env python3
"""Pack profit's recipe data into addons/ForeverGPS/Data/Recipes.lua.

    python tools/recipes_import.py          # write it
    python tools/recipes_import.py --check  # fail if it is out of date

Source: third_party/profit/Data/Recipes.lua and Data/Items.lua, from
https://github.com/ExcEssIv3/profit at commit 823413b (MIT, (c) 2026 seth), which its
tools/build_recipes.py generated from the WoW Forever client's own tables (build
1.60.1.70790). The facts are the game's; see docs/REUSE.md.

Each recipe becomes one string, so 2,486 recipes cost about as much memory as their text:

    "line|item:count|reagent:n,reagent:n|learn|trainer|yellow|grey|sources|recipeItem:skill,...|issues"

line is the client's skill line ID (171 is Alchemy), so nothing depends on the language;
a recipe of two professions lists both, "165,197".
Sources are letters: t trainer (seen at one in game, or learned with the profession), i a
recipe item, f no recipe item exists so probably a trainer, u the client data is incomplete.
An empty field is unknown, never zero. Names are left out: the game gives them.

Merchant reagents: items profit's author lists as sold by merchants without limit, with
the client's listed price per item in copper.
Standard library only.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "profit" / "Data"
OUT = ROOT / "addons" / "ForeverGPS" / "Data" / "Recipes.lua"

LINES = {
    "Blacksmithing": 164, "Leatherworking": 165, "Alchemy": 171, "Cooking": 185, "Mining": 186,
    "Tailoring": 197, "Engineering": 202, "Enchanting": 333, "First Aid": 129,
}
SOURCES = {"trainer": "t", "item": "i", "trainer_inferred": "f", "unknown": "u"}
ROW = re.compile(r'^  \[(\d+)\]=\{n="(?:[^"\\]|\\.)*",(.*)\},$')
FIELD = re.compile(r'(\w+)=(\{[^}]*\}|-?\d+|"[^"]*")')


def nums(text: str) -> list[int]:
    return [int(v) for v in re.findall(r"-?\d+", text)]


def pairs(values: list[int]) -> str:
    return ",".join(f"{values[i]}:{values[i + 1]}" for i in range(0, len(values), 2))


def recipes() -> list[tuple[int, str]]:
    out = []
    text = (SRC / "Recipes.lua").read_text(encoding="utf-8")
    for line in text.split("\n"):
        m = ROW.match(line)
        if not m:
            continue
        spell, rest = int(m.group(1)), m.group(2)
        f = {k: v for k, v in FIELD.findall(rest)}
        prof = f["p"].strip('"')
        sources = "".join(SOURCES[s] for s in re.findall(r'"(\w+)"', f.get("s", "{}")))
        issues = ",".join(re.findall(r'"(\w+)"', f.get("x", "{}")))
        make = nums(f.get("m", "{}"))
        packed = "|".join([
            str(LINES[prof]),
            f"{make[0]}:{make[1]}" if make else "",
            pairs(nums(f.get("r", "{}"))),
            f.get("l", ""), f.get("t", ""), f.get("y", ""), f.get("g", ""),
            sources,
            pairs(nums(f.get("ri", "{}"))),
            issues,
        ])
        out.append((spell, packed))
    if len(out) < 2000:
        raise SystemExit(f"recipes_import: only {len(out)} recipes read; has the source format changed?")
    # A spell listed twice: the same recipe twice (kept once), or one recipe of two
    # professions (its lines joined, "165,197"). Anything else differing is an error.
    merged: dict[int, list[str]] = {}
    for spell, packed in out:
        fields = packed.split("|")
        if spell not in merged:
            merged[spell] = fields
            continue
        have = merged[spell]
        if have[1:] != fields[1:]:
            raise SystemExit(f"recipes_import: spell {spell} is listed twice with different data")
        lines = have[0].split(",")
        if fields[0] not in lines:
            have[0] = ",".join(sorted(lines + [fields[0]], key=int))
    return sorted((spell, "|".join(fields)) for spell, fields in merged.items())


def vendor() -> list[tuple[int, int]]:
    out = []
    text = (SRC / "Items.lua").read_text(encoding="utf-8")
    for m in re.finditer(r'^  \[(\d+)\]=\{n="(?:[^"\\]|\\.)*",q=\d+,b=(\d+),v=\d+,vs=1\},$', text, re.M):
        if int(m.group(2)) > 0:
            out.append((int(m.group(1)), int(m.group(2))))
    return sorted(out)


def render() -> str:
    build = re.search(r'ns\.DataBuild = "([^"]+)"', (SRC / "Recipes.lua").read_text(encoding="utf-8")).group(1)
    rows = [
        "-- Generated by tools/recipes_import.py. Do not edit.",
        "--",
        "-- From profit, https://github.com/ExcEssIv3/profit, commit 823413b68211d37321501d4fc556a89e1b5ed426,",
        "-- MIT License, Copyright (c) 2026 seth (Licenses/profit-LICENSE.txt). profit generated it from",
        f"-- the WoW Forever client's own tables, build {build}: the facts are the game's. Packed per",
        "-- recipe as \"line|item:count|reagents|learn|trainer|yellow|grey|sources|recipeItems|issues\".",
        "-- See tools/recipes_import.py and docs/REUSE.md.",
        "ForeverGPS.RecipeData = {",
        f'    build = "{build}",',
        "    recipes = {",
    ]
    rows += [f'        [{spell}] = "{packed}",' for spell, packed in recipes()]
    rows += ["    },", "    -- Reagents merchants sell without limit, with the client's listed price in copper.", "    vendor = {"]
    rows += [f"        [{item}] = {price}," for item, price in vendor()]
    rows += ["    },", "}", ""]
    return "\n".join(rows)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        same = OUT.is_file() and OUT.read_bytes() == text.encode("utf-8")
        print("recipes_import: up to date" if same else "recipes_import: out of date")
        return 0 if same else 1
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print(f"recipes_import: wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
